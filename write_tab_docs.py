def find_free_cell(ws):
    """یافتن اولین سلول خالی در ردیف ۱ (بعد از آخرین ستون با داده)"""
    row1 = ws.row_values(1)
    # اگر ردیف ۱ خالی است، از A1 شروع کن
    if not row1:
        return 'A1'
    # اولین ستون خالی بعد از داده‌ها
    last_col = len(row1)
    # پیدا کردن آخرین ستون با داده واقعی
    while last_col > 0 and (not row1[last_col-1].strip()):
        last_col -= 1
    # ستون بعدی (۱-based)
    next_col = last_col + 2  # یک ستون فاصله
    # تبدیل به حرف (A, B, ..., Z, AA, AB, ...)
    col_letter = ''
    n = next_col
    while n > 0:
        n, rem = divmod(n - 1, 26)
        col_letter = chr(65 + rem) + col_letter
    return f'{col_letter}1'


def main():
    e = load_env()
    sid = e.get('SHEET_ID') or e.get('GOOGLE_SHEET_ID')
    gc = gspread.service_account(filename='service_account.json')
    sh = gc.open_by_key(sid) if sid else gc.open('نمادهای معاملاتی')

    print('=' * 72)
    print('نوشتن توضیحات اهداف و دستورالعمل هر تب')
    print('=' * 72)

    for ws in sh.worksheets():
        title = ws.title
        if title not in TAB_DOCS:
            print(f'  ⚠ {title}: بدون توضیحات (ناشناخته)')
            continue

        doc = TAB_DOCS[title]
        cell = find_free_cell(ws)

        try:
            ws.update(values=[[doc]], range_name=f'{cell}:{cell}')
            print(f'  ✓ {title}: توضیحات در {cell} نوشته شد ({len(doc)} کاراکتر)')
        except Exception as ex:
            print(f'  ✗ {title}: خطا — {ex}')

    print()
    print('=' * 72)
    print('✓ تکمیل شد. هر تب اکنون توضیحات اهداف خود را دارد.')
    print('=' * 72)


if __name__ == '__main__':
    main()
